// Gives every dish a permanent ID (TT-0001, TT-0002, …) and writes src/data/dish-ids.js.
// IDs are never reused or changed: dishes that already have one keep it, new dishes get the next number.
// Run `pnpm assign-ids` after adding dishes (validation fails until you do).
// Renaming a dish? Edit its key in src/data/dish-ids.js by hand so it keeps the same ID.
import fs from 'node:fs';
import { DISHES } from '../src/data.js';
import { DISH_IDS } from '../src/data/dish-ids.js';

const ids = { ...DISH_IDS };
let next = Math.max(0, ...Object.values(ids).map((v) => parseInt(v.slice(3), 10))) + 1;
// the very first run numbers dishes by popularity, so the best known dishes get the lowest numbers
const fresh = DISHES.filter((d) => !ids[d.name]).sort((a, b) => b.popularity - a.popularity || a.id - b.id);
for (const d of fresh) ids[d.name] = `TT-${String(next++).padStart(4, '0')}`;
const lines = Object.entries(ids).sort((a, b) => a[1].localeCompare(b[1])).map(([name, id]) => `  ${JSON.stringify(name)}: '${id}',`);
fs.writeFileSync(new URL('../src/data/dish-ids.js', import.meta.url), `// Permanent dish IDs. Never reuse or renumber. Generated by \`pnpm assign-ids\`; see scripts/assign-dish-ids.mjs.\nexport const DISH_IDS = {\n${lines.join('\n')}\n};\n`);
console.log(`${fresh.length} new dish ID${fresh.length === 1 ? '' : 's'} assigned (${Object.keys(ids).length} in total)`);
