// Gives every dish and every ingredient a permanent ID and writes src/data/dish-ids.js and src/data/ingredient-ids.js.
//   dishes:       TT-0001, TT-0002, …        ingredients:  TI-0001, TI-0002, …
// IDs are never reused or changed: items that already have one keep it, new ones get the next number.
// Run `pnpm assign-ids` after adding dishes or ingredients (validation fails until you do).
// Renaming one? Edit its key in the ids file by hand so it keeps the same ID.
import fs from 'node:fs';
import { DISHES, INGREDIENT_CATEGORY } from '../src/data.js';
import { DISH_IDS } from '../src/data/dish-ids.js';
import { INGREDIENT_IDS } from '../src/data/ingredient-ids.js';

function assign(existing, names, prefix, rank) {
  const ids = { ...existing };
  let next = Math.max(0, ...Object.values(ids).map((v) => parseInt(v.slice(3), 10))) + 1;
  const fresh = names.filter((n) => !ids[n]).sort(rank);
  for (const n of fresh) ids[n] = `${prefix}-${String(next++).padStart(4, '0')}`;
  return { ids, fresh: fresh.length };
}
function write(file, header, exportName, ids) {
  const lines = Object.entries(ids).sort((a, b) => a[1].localeCompare(b[1])).map(([name, id]) => `  ${JSON.stringify(name)}: '${id}',`);
  fs.writeFileSync(new URL(`../src/data/${file}`, import.meta.url), `// ${header} Never reuse or renumber. Generated by \`pnpm assign-ids\`; see scripts/assign-dish-ids.mjs.\nexport const ${exportName} = {\n${lines.join('\n')}\n};\n`);
}

// the very first run numbers items by popularity / use, so the best known ones get the lowest numbers
const pop = new Map(DISHES.map((d) => [d.name, d.popularity]));
const order = new Map(DISHES.map((d) => [d.name, d.id]));
const dishes = assign(DISH_IDS, DISHES.map((d) => d.name), 'TT', (a, b) => pop.get(b) - pop.get(a) || order.get(a) - order.get(b));
write('dish-ids.js', 'Permanent dish IDs.', 'DISH_IDS', dishes.ids);
const used = new Map();
for (const d of DISHES) for (const nm of new Set(d.ingredients)) used.set(nm, (used.get(nm) || 0) + 1);
const ingredients = assign(INGREDIENT_IDS, Object.keys(INGREDIENT_CATEGORY), 'TI', (a, b) => (used.get(b) || 0) - (used.get(a) || 0) || a.localeCompare(b));
write('ingredient-ids.js', 'Permanent ingredient IDs.', 'INGREDIENT_IDS', ingredients.ids);
console.log(`${dishes.fresh} new dish ID${dishes.fresh === 1 ? '' : 's'} (${Object.keys(dishes.ids).length} in total); ${ingredients.fresh} new ingredient ID${ingredients.fresh === 1 ? '' : 's'} (${Object.keys(ingredients.ids).length} in total)`);
