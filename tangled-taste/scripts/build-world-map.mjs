// Builds src/data/worldMap.js: country outlines for the "Full Earth" globe setting.
//
//   node scripts/build-world-map.mjs path/to/ne_110m_admin_0_countries.geojson
//
// Source: Natural Earth admin-0 countries, 1:110m (public domain, https://www.naturalearthdata.com).
// Output: a list of polygons; each polygon is a list of rings; each ring is a flat [lng, lat, lng, lat, …] list
// rounded to 0.1 degree. The file is loaded only when Full Earth is selected.
import fs from 'node:fs';

const src = process.argv[2];
if (!src) throw new Error('usage: node scripts/build-world-map.mjs <ne_110m_admin_0_countries.geojson>');
const world = JSON.parse(fs.readFileSync(src, 'utf8'));
const round = (v) => Math.round(v * 10) / 10;
const polygons = [];
for (const f of world.features) {
  if (f.properties.ADMIN === 'Antarctica') continue; // a ring of ice around the bottom of the map adds nothing
  const g = f.geometry;
  for (const poly of g.type === 'Polygon' ? [g.coordinates] : g.coordinates) {
    polygons.push(poly.map((ring) => {
      const flat = [];
      let last = null;
      for (const [x, y] of ring) {
        const p = [round(x), round(y)];
        if (last && last[0] === p[0] && last[1] === p[1]) continue; // drop repeats created by rounding
        flat.push(p[0], p[1]);
        last = p;
      }
      return flat;
    }));
  }
}
const out = `// Country outlines for the Full Earth globe setting. Generated by scripts/build-world-map.mjs from Natural Earth 1:110m (public domain).\nexport default ${JSON.stringify(polygons)};\n`;
fs.writeFileSync(new URL('../src/data/worldMap.js', import.meta.url), out);
console.log(`${polygons.length} polygons, ${(out.length / 1024).toFixed(0)} KB`);
